// The artifact you leave with: a plan you can act on away from the screen.
import { money, fmtDate, projectedSavings } from './insights.js';

const VERDICT_ORDER = { cancel: 0, review: 1, keep: 2, ended: 3 };

function decisionFor(s, decisions) {
  return decisions[s.key] || s.verdict;
}

export function toMarkdown(result, decisions = {}, options = {}) {
  const now = options.now || new Date();
  const rows = [...result.series].sort((a, b) => {
    const d = VERDICT_ORDER[decisionFor(a, decisions)] - VERDICT_ORDER[decisionFor(b, decisions)];
    return d !== 0 ? d : b.annualCost - a.annualCost;
  });

  const savings = projectedSavings(result.series, decisions);
  const lines = [];
  lines.push('# Subscription action plan');
  lines.push('');
  lines.push(`Generated ${fmtDate(now)} from ${result.stats.transactions} transactions across ${result.stats.spanDays} days.`);
  lines.push('');
  lines.push(`- **Active subscriptions:** ${result.summary.activeCount}`);
  lines.push(`- **Committed spend:** ${money(result.summary.monthlyTotal)}/mo · ${money(result.summary.annualTotal)}/yr`);
  if (savings > 0) lines.push(`- **Cancelling what you marked saves:** ${money(savings)}/yr`);
  lines.push('');

  for (const group of ['cancel', 'review', 'keep', 'ended']) {
    const inGroup = rows.filter((s) => decisionFor(s, decisions) === group);
    if (inGroup.length === 0) continue;
    lines.push(`## ${heading(group)}`);
    lines.push('');
    for (const s of inGroup) {
      lines.push(`### ${s.name} — ${money(s.currentAmount)} ${s.cadenceLabel.toLowerCase()} (${money(s.annualCost)}/yr)`);
      lines.push('');
      lines.push(`- Category: ${s.category}`);
      lines.push(`- Charges seen: ${s.count} (${fmtDate(s.firstSeen)} → ${fmtDate(s.lastSeen)})`);
      if (!s.ended) lines.push(`- Next charge expected: ${fmtDate(s.nextExpected)}`);
      for (const f of s.flags) lines.push(`- **${f.label}:** ${f.detail}`);
      lines.push('');
    }
  }

  lines.push('---');
  lines.push('');
  lines.push('Generated by Subscription X-Ray. Every figure above comes from your own statement; nothing was uploaded.');
  return lines.join('\n');
}

function heading(group) {
  return {
    cancel: 'Cancel these',
    review: 'Worth a decision',
    keep: 'Keep',
    ended: 'Already stopped charging',
  }[group];
}

export function toCsv(result, decisions = {}) {
  const header = [
    'merchant', 'category', 'decision', 'amount', 'cadence', 'annual_cost',
    'charges_seen', 'first_seen', 'last_seen', 'next_expected', 'confidence', 'flags',
  ];
  const rows = result.series.map((s) => [
    s.name,
    s.category,
    decisionFor(s, decisions),
    s.currentAmount.toFixed(2),
    s.cadenceLabel,
    s.annualCost.toFixed(2),
    String(s.count),
    iso(s.firstSeen),
    iso(s.lastSeen),
    s.ended ? '' : iso(s.nextExpected),
    s.confidence.toFixed(2),
    s.flags.map((f) => f.id).join(' '),
  ]);
  return [header, ...rows].map((r) => r.map(escapeCell).join(',')).join('\n');
}

function iso(d) {
  return d.toISOString().slice(0, 10);
}

function escapeCell(value) {
  const s = String(value);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
